#!/usr/bin/env node
// Generates the per-workflow knowledge coverage matrix in
// .claude/workflows/MANIFEST.md. Rewrites ONLY the region between the
// BEGIN/END KNOWLEDGE MATRIX sentinels; the hand-maintained iteration history
// above/below is preserved verbatim. Run after porting/seedimg a workflow:
//   node scripts/workflow-knowledge-manifest.mjs
//
// The matrix is an INVENTORY concern (what exists, how many records, last run);
// correctness (snippet match, schema presence) is the checker's job
// (scripts/check-workflow-patterns.mjs). They are complementary.
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const WF_DIR = join(__dirname, "..", ".claude", "workflows");
const MANIFEST = join(WF_DIR, "MANIFEST.md");

// ASCII-only sentinels so matching never breaks on an em-dash or re-encoding.
const BEGIN = "<!-- BEGIN KNOWLEDGE MATRIX -->";
const END = "<!-- END KNOWLEDGE MATRIX -->";

// meta.name is guaranteed == filename (minus .js) by the checker's
// "meta.name <-> filename" hard rule, so derive the workflow name from the file.
function scanWorkflowJs(fileName, src) {
  const name = fileName.replace(/\.js$/, "");
  return {
    name,
    family: name.startsWith("gui-") ? "gui" : name.startsWith("mlx-") ? "mlx" : "—",
    load: /async function loadKnowledge\s*\(/.test(src),
    extract: /async function extractKnowledge\s*\(/.test(src),
    saveHistory: /async function saveHistory\s*\(/.test(src),
  };
}

function scanKnowledgeFile(path) {
  if (!existsSync(path)) return { exists: false, total: 0, active: 0, lastRun: "pending" };
  const raw = readFileSync(path, "utf8");
  const lines = raw.split("\n").filter((l) => l.trim() !== "");
  if (lines.length === 0) return { exists: true, total: 0, active: 0, lastRun: "empty" };
  let active = 0;
  let lastRun = "—";
  for (const line of lines) {
    try {
      const rec = JSON.parse(line);
      if (rec.status === "active") active++;
      if (rec.extracted_at) lastRun = rec.extracted_at; // append-order: last line wins
    } catch {
      /* skip unparseable line */
    }
  }
  return { exists: true, total: lines.length, active, lastRun };
}

const jsFiles = readdirSync(WF_DIR).filter((f) => f.endsWith(".js")).sort();

const rows = jsFiles.map((f) => {
  const src = readFileSync(join(WF_DIR, f), "utf8");
  const w = scanWorkflowJs(f, src);
  const kb = scanKnowledgeFile(join(WF_DIR, `${w.name}.knowledge.jsonl`));
  return { ...w, ...kb };
});

const totals = {
  workflows: rows.length,
  load: rows.filter((r) => r.load).length,
  extract: rows.filter((r) => r.extract).length,
  files: rows.filter((r) => r.exists).length,
  records: rows.reduce((s, r) => s + r.total, 0),
  active: rows.reduce((s, r) => s + r.active, 0),
};

const matrix = [
  BEGIN,
  "",
  "> _Generated by `scripts/workflow-knowledge-manifest.mjs` — do not edit by hand. Run after porting/seeding a workflow._",
  "",
  "| Workflow | Family | load | extract | saveHistory | kb file | records | active | last run |",
  "|---|---|:---:|:---:|:---:|:---:|---:|---:|---|",
  ...rows.map((r) =>
    `| ${r.name} | ${r.family} | ${r.load ? "✓" : "—"} | ${r.extract ? "✓" : "—"} | ${r.saveHistory ? "✓" : "—"} | ${r.exists ? "✓" : "pending"} | ${r.total} | ${r.active} | ${r.lastRun} |`
  ),
  "",
  `**Totals:** ${totals.workflows} workflows · ${totals.load} load / ${totals.extract} extract wired · ${totals.files} knowledge files · ${totals.records} records (${totals.active} active)`,
  "",
  END,
].join("\n");

let manifest;
if (existsSync(MANIFEST)) {
  manifest = readFileSync(MANIFEST, "utf8");
  if (manifest.includes(BEGIN) && manifest.includes(END)) {
    const before = manifest.slice(0, manifest.indexOf(BEGIN));
    const after = manifest.slice(manifest.indexOf(END) + END.length);
    manifest = before + matrix + after;
  } else {
    manifest = manifest.trimEnd() + "\n\n" + matrix + "\n";
  }
} else {
  manifest =
    `# Dynamic-Workflow Knowledge — MANIFEST\n\n` +
    `> Iteration history (manual changelog — append each iteration) + a GENERATED\n` +
    `> coverage matrix below (between the sentinels — do not edit by hand).\n\n` +
    `## Iteration history\n\n` +
    `_(populate this section as iterations land)_\n\n` +
    matrix + "\n";
}

writeFileSync(MANIFEST, manifest);
console.log(`Manifest written → ${MANIFEST}`);
console.log(`  ${totals.workflows} workflows · ${totals.files} knowledge files · ${totals.records} records (${totals.active} active)`);
